const { execSync } = require("child_process");
const https = require("https");
const { GoogleGenerativeAI } = require("@google/generative-ai");

const GEMINI_API_KEY = process.env.GEMINI_API_KEY;
const GEMINI_MODEL = process.env.GEMINI_MODEL || "gemini-2.5-flash";

let genAI;

function initializeGenAI() {
  if (!GEMINI_API_KEY) {
    throw new Error("Missing GEMINI_API_KEY environment variable");
  }
  genAI = new GoogleGenerativeAI(GEMINI_API_KEY);
}

function postPRComment(body) {
  const prNumber = process.env.GITHUB_REF?.split("/")[2];
  const repo = process.env.GITHUB_REPOSITORY;
  const token = process.env.GITHUB_TOKEN;

  if (!prNumber || !repo || !token) {
    console.log("Not running in PR context, skipping comment.");
    return Promise.resolve();
  }

  const data = JSON.stringify({ body });

  return new Promise((resolve, reject) => {
    const req = https.request(
      {
        hostname: "api.github.com",
        path: `/repos/${repo}/issues/${prNumber}/comments`,
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          "Content-Length": Buffer.byteLength(data),
          "Authorization": `Bearer ${token}`,
          "User-Agent": "shift-left-ai-agent"
        },
      },
      (res) => {
        let response = "";
        res.on("data", chunk => response += chunk);
        res.on("end", () => {
          if (res.statusCode >= 200 && res.statusCode < 300) {
            console.log("✅ PR comment posted successfully");
            resolve(response);
          } else {
            reject(new Error(`Failed to post comment: ${res.statusCode}`));
          }
        });
      }
    );

    req.on("error", (err) => {
      console.error("❌ Error posting PR comment:", err.message);
      reject(err);
    });
    req.write(data);
    req.end();
  });
}


async function runAudit() {
  try {
    const output = execSync("npm audit --json", { encoding: "utf8" });
    return JSON.parse(output);
  } catch (err) {
    if (err.stdout) {
      return JSON.parse(err.stdout);
    }
    throw err;
  }
}

function extractVulnerabilities(auditJson) {
  if (!auditJson.vulnerabilities) return [];

  const results = [];

  for (const [pkg, details] of Object.entries(auditJson.vulnerabilities)) {
    results.push({
      package: pkg,
      severity: details.severity,
      via: details.via,
      fixAvailable: details.fixAvailable,
    });
  }

  return results;
}

function callGemini(prompt) {
  const model = genAI.getGenerativeModel({ model: GEMINI_MODEL });
  return model.generateContent(prompt).then(result => result.response.text());
}

// Retry logic with exponential backoff
async function callWithRetry(fn, maxRetries = 3, baseDelayMs = 2000) {
  for (let attempt = 0; attempt < maxRetries; attempt++) {
    try {
      return await fn();
    } catch (error) {
      if (error.status === 429 && attempt < maxRetries - 1) {
        const delayMs = baseDelayMs * Math.pow(2, attempt);
        console.warn(`⏳ Rate limited (429). Retrying in ${delayMs}ms... (attempt ${attempt + 1}/${maxRetries})`);
        await new Promise(resolve => setTimeout(resolve, delayMs));
      } else {
        throw error;
      }
    }
  }
}

(async () => {
  try {
    initializeGenAI();
    
    const auditJson = await runAudit();
    const vulns = extractVulnerabilities(auditJson);

    if (vulns.length === 0) {
      console.log("✅ No dependency vulnerabilities detected.");
      process.exit(0);
    }

    console.log("🚨 Vulnerable packages detected:");
    console.log(JSON.stringify(vulns, null, 2));

    const prompt = `
You are a software supply-chain security expert.

Analyze the following npm dependency vulnerabilities.

For each package:
- Explain the risk briefly
- Suggest the safest upgrade version
- Suggest an alternative package if recommended
- Classify risk as Critical / High / Medium / Low
- Keep response structured and concise

Vulnerabilities:
${JSON.stringify(vulns, null, 2)}
`;

    const aiResponse = await callWithRetry(async () => {
      return await callGemini(prompt);
    });

    console.log("\n🧠 AI Dependency Risk Analysis:\n");
    console.log(aiResponse);
    
    const markdownComment = `
## 🛡 Dependency Risk Intelligence Report

${aiResponse}

---
*Generated by Shift-Left AI Security Agent*
`;

    // Post comment to PR
    try {
      await postPRComment(markdownComment);
    } catch (commentError) {
      console.error("⚠️ Warning: Could not post PR comment:", commentError.message);
      // Don't fail the entire job if comment fails
    }

    // Fail pipeline if high severity present
    const hasHigh = vulns.some(v =>
      ["high", "critical"].includes(v.severity)
    );

    if (hasHigh) {
      console.log("\n❌ High/Critical dependency risk detected.");
      process.exit(1);
    } else {
      process.exit(0);
    }
  } catch (error) {
    console.error("❌ Error:", error.message);
    process.exit(1);
  }
})();
